/*
 * Optional maintenance tool (NOT needed to run or deploy the site).
 *
 * Writes supabase/seed-projects.sql from the built-in project list in
 * js/projects-data.js, so the database starts with the same projects.
 *
 * Usage (from the project root):
 *     node tools/build-seed-sql.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const sandbox = { window: { SD_CONFIG: {} }, console };
vm.createContext(sandbox);
// Read the list without contacting the database: expose the internal array.
const src = fs.readFileSync(path.join(root, 'js', 'projects-data.js'), 'utf8')
  .replace("SD.api = {", "SD.__builtin = P;\n  SD.api = {");
vm.runInContext(src, sandbox);
const projects = sandbox.window.SD.__builtin;

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const rows = projects.map((p) => {
  const images = (p.media || []).map((m) => ({
    url: m.media_url, kind: m.media_type === 'plan' ? 'plan' : 'image', alt: m.alt_text,
    width: m.width || null, height: m.height || null
  }));
  return '(' + [
    q(p.slug), q(p.title), q(p.subtitle), q(p.category), q(p.project_type), q(p.status), q(p.location), q(p.area),
    q(p.client), q(p.short_description), q(p.description), q(p.details), q(JSON.stringify(images)) + '::jsonb',
    p.featured ? 'true' : 'false', String(p.sort_order || 100), 'true'
  ].join(',\n   ') + ')';
});

const sql = `-- =====================================================================
-- SPACE DESIGN — starting projects (generated by tools/build-seed-sql.js)
-- Run in Supabase → SQL Editor AFTER schema.sql. Safe to re-run: projects
-- whose slug already exists are left unchanged.
-- Images point to the files already on the website (assets/img/projects/).
-- =====================================================================
insert into public.projects
  (slug, title, subtitle, category, project_type, status, location, area,
   client, short_description, description, details, images, featured, sort_order, published)
values
${rows.join(',\n')}
on conflict (slug) do nothing;
`;

fs.writeFileSync(path.join(root, 'supabase', 'seed-projects.sql'), sql);
console.log('wrote supabase/seed-projects.sql with ' + rows.length + ' projects');
